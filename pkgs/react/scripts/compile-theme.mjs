import { writeFile } from 'node:fs/promises';
import MagicString from 'magic-string';
import { createGenerator } from 'unocss';
import config from '../uno.config.mjs';
import { recipes } from './recipes.mjs';

// Compile the finite set of UI slots once for both source and packed consumers.
// The linked stylesheet lives inside the shadow root; no host bundler plugin or CSS import.
const uno = await createGenerator(config);
const tokens = new Set();
const classes = {};
for (const [slot, utilities] of Object.entries(recipes)) {
  let source = `className="${utilities}"`;
  for (const transformer of config.transformers) {
    const code = new MagicString(source);
    await transformer.transform(code, 'slots.tsx', { uno, tokens, invalidate() {} });
    source = code.toString();
  }
  const name = source.match(/^className="(kk-[\w-]+)"$/)?.[1];
  if (!name) throw new Error(`Uncompiled slot ${slot}: ${source}`);
  classes[slot] = name;
}
const { css } = await uno.generate(tokens, { minify: true });
await writeFile(new URL('../src/dev-tools/theme.generated.ts', import.meta.url),
  `// Generated by pnpm theme; edit scripts/recipes.mjs.\nexport const ui = ${JSON.stringify(classes, null, 2)} as const;\nexport const stylesheet = 'data:text/css;base64,${Buffer.from(css).toString('base64')}';\n`);
